var documentID = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_-]*$`)
var ErrDuplicateID = errors.New("duplicate document ID")

// Document includes means-owned id/title and application data in Frontmatter.
// filename is storage bookkeeping, never the identity exposed to consumers.
type Document struct {
	ID          string         `json:"id"`
	Hash        string         `json:"hash"`
	Frontmatter map[string]any `json:"frontmatter"`
	Body        string         `json:"body"`
	Markdown    string         `json:"-"`
	filename    string
}

type DocumentSummary struct {
	ID          string         `json:"id"`
	Frontmatter map[string]any `json:"frontmatter"`
	Path        string         `json:"path,omitempty"` // Only included for diagnostics.
	Error       string         `json:"error,omitempty"`
}

type ListResult struct {
	Documents []DocumentSummary `json:"documents"`
	HasMore   bool              `json:"has_more"`
}

func normalizeObject(value map[string]any) (map[string]any, error) {
	encoded, err := json.Marshal(value)
	if err != nil {
		return nil, fmt.Errorf("encode frontmatter: %w", err)
	}
	decoded, err := jsonschema.UnmarshalJSON(bytes.NewReader(encoded))
	if err != nil {
		return nil, err
	}
	object, ok := decoded.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("frontmatter must be an object")
	}
	return object, nil
}

// Create accepts title and optional data, generates an immutable ID, and stores
// <id>-<title-slug>.md. The collection schema validates only data.
func (c *Collection) Create(frontmatter map[string]any, body string) (*Document, error) {
	if _, supplied := frontmatter["id"]; supplied {
		return nil, fmt.Errorf("id is generated by means; omit it from creation input")
	}
	frontmatter, err := normalizeObject(frontmatter)
	if err != nil {
		return nil, err
	}
	if _, exists := frontmatter["data"]; !exists {
		frontmatter["data"] = map[string]any{}
	}
	// Validate everything before touching the filesystem. The placeholder is
	// replaced with a generated ID after validation.
	frontmatter["id"] = "pending"
	if err := c.Validate(frontmatter); err != nil {
		return nil, err
	}
	if !utf8.ValidString(body) {
		return nil, fmt.Errorf("body must be valid UTF-8")
	}
	root, err := os.OpenRoot(c.Path)
	if err != nil {
		return nil, err
	}
	defer root.Close()
	for {
		id, err := generateID()
		if err != nil {
			return nil, err
		}
		doc, err := createCandidate(root, id, frontmatter, body)
		if errors.Is(err, os.ErrExist) {
			continue
		}
		return doc, err
	}
}

func generateID() (string, error) {
	const alphabet = "0123456789abcdefghjkmnpqrstvwxyz"
	// 32 equally likely symbols; no modulo bias, case folding, or punctuation.
	var random [5]byte
	if _, err := rand.Read(random[:]); err != nil {
		return "", fmt.Errorf("generate document ID: %w", err)
	}
	for i := range random {
		random[i] = alphabet[random[i]&31]
	}
	return string(random[:]), nil
}

func createCandidate(root *os.Root, id string, frontmatter map[string]any, body string) (*Document, error) {
	// An exclusive allocation file prevents concurrent means creators from using
	// the same candidate, even with different titles. Crashed allocations are
	// simply skipped on a future collision; no stale-lock recovery is needed.
	allocation := ".means-create-" + id + ".tmp"
	reservation, err := root.OpenFile(allocation, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return nil, err
	}
	defer root.Remove(allocation)
	if err := reservation.Close(); err != nil {
		return nil, err
	}
	entries, err := scanDocuments(root)
	if err != nil {
		return nil, err
	}
	for _, entry := range entries {
		if entry.doc != nil && entry.doc.ID == id {
			return nil, os.ErrExist
		}
	}
	frontmatter = mergeObject(frontmatter, map[string]any{"id": id})
	markdown, err := encodeMarkdown(frontmatter, body)
	if err != nil {
		return nil, err
	}
	filename := id + "-" + titleSlug(frontmatter["title"].(string)) + ".md"
	file, err := root.OpenFile(filename, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		return nil, fmt.Errorf("create document: %w", err)
	}
	_, writeErr := file.WriteString(markdown)
	if err := errors.Join(writeErr, file.Close()); err != nil {
		return nil, fmt.Errorf("write document: %w", errors.Join(err, root.Remove(filename)))
	}
	return &Document{ID: id, Hash: contentHash(markdown), Frontmatter: frontmatter, Body: body, Markdown: markdown, filename: filename}, nil
}

// Keep filenames readable and bounded without interpreting titles as paths.
func titleSlug(title string) string {
	var out strings.Builder
	separator := false
	for _, r := range strings.ToLower(title) {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			separator = out.Len() > 0
			continue
		}
		extra := utf8.RuneLen(r)
		if separator {
			extra++
		}
		if out.Len()+extra > 80 {
			break
		}
		if separator {
			out.WriteByte('-')
			separator = false
		}
		out.WriteRune(r)
	}
	if out.Len() == 0 {
		return "document"
	}
	return out.String()
}

// Read resolves a stored frontmatter ID regardless of filename or subdirectory.
// Application schema violations remain readable; the means envelope must be valid.
func (c *Collection) Read(id string) (*Document, error) {
	if err := validateDocumentID(id); err != nil {
		return nil, err
	}
	root, err := os.OpenRoot(c.Path)
	if err != nil {
		return nil, err
	}
	defer root.Close()
	return readDocument(root, id)
}

func validateDocumentID(id string) error {
	if len(id) > 128 || !documentID.MatchString(id) {
		return fmt.Errorf("invalid document ID %q; use the stored id (1–128 letters, digits, - and _, starting with a letter or digit), not a filename or path", id)
	}
	return nil
}

func validateEnvelope(frontmatter map[string]any) error {
	for key := range frontmatter {
		if key != "id" && key != "title" && key != "data" {
			return fmt.Errorf("unknown means frontmatter field %q; application fields belong under data", key)
		}
	}
	id, ok := frontmatter["id"].(string)
	if !ok {
		return fmt.Errorf("frontmatter.id must be a string")
	}
	if err := validateDocumentID(id); err != nil {
		return err
	}
	title, ok := frontmatter["title"].(string)
	if !ok || strings.TrimSpace(title) == "" || !utf8.ValidString(title) {
		return fmt.Errorf("frontmatter.title must be a nonempty UTF-8 string")
	}
	if _, ok := frontmatter["data"].(map[string]any); !ok {
		return fmt.Errorf("frontmatter.data must be an object")
	}
	return nil
}

func contentHash(markdown string) string {
	sum := sha256.Sum256([]byte(markdown))
	return hex.EncodeToString(sum[:])
}

type storedDocument struct {
	filename string
	doc      *Document
	err      error
}

// Walk visible Markdown files, excluding instructions and symlinks. Scan the
// whole collection even for limited lists so duplicates outside the limit count.
func scanDocuments(root *os.Root) ([]storedDocument, error) {
	var entries []storedDocument
	err := fs.WalkDir(root.FS(), ".", func(filename string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if filename != "." && strings.HasPrefix(entry.Name(), ".") {
			if entry.IsDir() {
				return fs.SkipDir
			}
			return nil
		}
		if !entry.Type().IsRegular() || !strings.HasSuffix(filename, ".md") || filename == InstructionsFilename {
			return nil
		}
		doc, err := readDocumentFile(root, filename)
		entries = append(entries, storedDocument{filename: filename, doc: doc, err: err})
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("scan documents: %w", err)
	}
	return entries, nil
}

func readDocumentFile(root *os.Root, filename string) (*Document, error) {
	info, err := root.Lstat(filename)
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() {
		return nil, fmt.Errorf("document %q must be a regular file", filename)
	}
	data, err := root.ReadFile(filename)
	if err != nil {
		return nil, err
	}
	frontmatter, body, err := parseMarkdown(data)
	if err != nil {
		return nil, fmt.Errorf("document %q: %w", filename, err)
	}
	id, _ := frontmatter["id"].(string)
	doc := &Document{ID: id, Hash: contentHash(string(data)), Frontmatter: frontmatter, Body: body, Markdown: string(data), filename: filename}
	if err := validateEnvelope(frontmatter); err != nil {
		return doc, fmt.Errorf("document %q: %w", filename, err)
	}
	return doc, nil
}

func readDocument(root *os.Root, id string) (*Document, error) {
	entries, err := scanDocuments(root)
	if err != nil {
		return nil, err
	}
	var match *storedDocument
	for i := range entries {
		entry := &entries[i]
		if entry.doc == nil || entry.doc.ID != id {
			continue
		}
		if match != nil {
			return nil, fmt.Errorf("%w %q in %q and %q; resolve the duplicate files", ErrDuplicateID, id, match.filename, entry.filename)
		}
		match = entry
	}
	if match == nil {
		return nil, fmt.Errorf("document ID %q: %w", id, os.ErrNotExist)
	}
	if match.err != nil {
		return nil, match.err
	}
	return match.doc, nil
}

// List returns frontmatter in relative filename order. Zero means no limit.
// Invalid documents and duplicate IDs produce individual diagnostic entries.
func (c *Collection) List(limit int) (*ListResult, error) {
	if limit < 0 {
		return nil, fmt.Errorf("limit must be zero or greater")
	}
	root, err := os.OpenRoot(c.Path)
	if err != nil {
		return nil, err
	}
	defer root.Close()
	entries, err := scanDocuments(root)
	if err != nil {
		return nil, err
	}
	counts := map[string]int{}
	for _, entry := range entries {
		if entry.doc != nil {
			counts[entry.doc.ID]++
		}
	}
	result := &ListResult{Documents: []DocumentSummary{}}
	for _, entry := range entries {
		if limit > 0 && len(result.Documents) == limit {
			result.HasMore = true
			break
		}
		summary := DocumentSummary{}
		if entry.doc != nil {
			summary.ID = entry.doc.ID
		}
		if summary.ID != "" && counts[summary.ID] > 1 {
			entry.err = fmt.Errorf("%w %q; resolve the duplicate files", ErrDuplicateID, summary.ID)
		}
		if entry.err != nil {
			summary.Path, summary.Error = path.Clean(entry.filename), entry.err.Error()
		} else {
			summary.Frontmatter = entry.doc.Frontmatter
		}
		result.Documents = append(result.Documents, summary)
	}
	return result, nil
}
